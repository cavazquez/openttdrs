/// ID global de un slot Action5 0x17.
#[must_use]
pub const fn rail_tunnel_base_sprite_id(climate: usize, slot: usize) -> Option<u32> {
    if climate < RAIL_TUNNEL_BASE_CLIMATE_COUNT && slot < RAIL_TUNNEL_BASE_SPRITE_COUNT {
        Some(SPR_RAILTYPE_TUNNEL_BASE + slot as u32)
    } else {
        None
    }
}

/// Slot nativo: ocho vistas normales o ocho nieve/desierto; cada
/// dirección ocupa dos sprites (rear, front).
#[must_use]
pub const fn rail_tunnel_base_slot(dir: u8, snow_or_desert: bool, front: bool) -> usize {
    (if snow_or_desert { 8 } else { 0 }) + ((dir as usize & 3) * 2) + if front { 1 } else { 0 }
}
